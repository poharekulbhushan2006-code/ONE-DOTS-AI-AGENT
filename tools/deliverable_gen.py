"""
MUSE Deliverable Generator: PowerPoint (PPTX) & Word (DOCX) Production Engine
Enables MUSE to generate genuine, downloadable presentation slides, study guides, reports, and whitepapers.
"""

import os
from pathlib import Path
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

from docx import Document
from docx.shared import Inches as DocxInches, Pt as DocxPt, RGBColor as DocxRGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

from tools.artifacts import artifact_vault


class DeliverableGenerator:
    """Generates production-grade PPTX and DOCX documents."""

    def __init__(self, agent_id: str = "dot-muse-04"):
        self.agent_id = agent_id

    def generate_presentation(
        self,
        title: str,
        subtitle: str,
        slides: List[Dict[str, Any]],
        output_filename: Optional[str] = None,
        task_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Generates a genuine Microsoft PowerPoint (.pptx) file.
        Each item in `slides` can contain:
        - "title": Slide header
        - "points": List of bullet points or text strings
        - "notes": Speaker notes for the presenter
        - "highlight": Optional key takeaway or statistic callout
        """
        prs = Presentation()
        # Set 16:9 widescreen dimensions (13.333 x 7.5 inches)
        prs.slide_width = Inches(13.333)
        prs.slide_height = Inches(7.5)

        # 1. Title Slide
        title_slide_layout = prs.slide_layouts[0]
        slide = prs.slides.add_slide(title_slide_layout)
        
        # Style Title
        title_box = slide.shapes.title
        title_box.text = title
        if title_box.text_frame.paragraphs:
            p = title_box.text_frame.paragraphs[0]
            p.font.size = Pt(40)
            p.font.bold = True
            p.font.color.rgb = RGBColor(16, 24, 40)

        # Style Subtitle
        if slide.placeholders and len(slide.placeholders) > 1:
            sub = slide.placeholders[1]
            sub.text = f"{subtitle}\nGenerated by ONE DOTS (MUSE Studio)"
            if sub.text_frame.paragraphs:
                p2 = sub.text_frame.paragraphs[0]
                p2.font.size = Pt(20)
                p2.font.color.rgb = RGBColor(90, 100, 120)

        # 2. Content Slides
        bullet_slide_layout = prs.slide_layouts[1]
        for s_data in slides:
            s = prs.slides.add_slide(bullet_slide_layout)
            
            # Slide Header
            s_title = s.shapes.title
            s_title.text = s_data.get("title", "Key Milestone")
            if s_title.text_frame.paragraphs:
                p = s_title.text_frame.paragraphs[0]
                p.font.size = Pt(28)
                p.font.bold = True
                p.font.color.rgb = RGBColor(24, 32, 50)

            # Slide Content Body
            body = s.placeholders[1]
            tf = body.text_frame
            tf.clear()

            points = s_data.get("points", [])
            for idx, pt_text in enumerate(points):
                p = tf.add_paragraph() if idx > 0 else tf.paragraphs[0]
                p.text = pt_text
                p.level = 0
                p.font.size = Pt(18)
                p.space_after = Pt(12)
                p.font.color.rgb = RGBColor(50, 60, 80)

            # Optional highlight callout
            highlight = s_data.get("highlight")
            if highlight:
                p_hi = tf.add_paragraph()
                p_hi.text = f"💡 Key Takeaway: {highlight}"
                p_hi.font.size = Pt(16)
                p_hi.font.bold = True
                p_hi.font.color.rgb = RGBColor(37, 99, 235)  # Royal Blue

            # Speaker Notes
            notes = s_data.get("notes")
            if notes and hasattr(s, "notes_slide"):
                s.notes_slide.notes_text_frame.text = notes

        # Save to temp file and register with ArtifactVault
        clean_name = (output_filename or f"{title.lower().replace(' ', '_')[:30]}.pptx")
        if not clean_name.endswith(".pptx"):
            clean_name += ".pptx"

        from config.settings import settings
        out_path = settings.DATA_DIR / "sandboxes" / self.agent_id / clean_name
        out_path.parent.mkdir(parents=True, exist_ok=True)
        prs.save(str(out_path))

        artifact = artifact_vault.register_file(
            agent_id=self.agent_id,
            name=clean_name,
            source_path=out_path,
            task_id=task_id,
            file_type="pptx",
            metadata={"slide_count": len(prs.slides), "title": title},
        )

        return {
            "success": True,
            "artifact_id": artifact.id,
            "filename": clean_name,
            "slide_count": len(prs.slides),
            "file_path": artifact.file_path,
            "download_url": f"/api/artifacts/{artifact.id}/download",
            "message": f"PowerPoint presentation '{clean_name}' with {len(prs.slides)} slides generated successfully."
        }

    def generate_document(
        self,
        title: str,
        subtitle: str,
        sections: List[Dict[str, Any]],
        output_filename: Optional[str] = None,
        task_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Generates a genuine Microsoft Word (.docx) report or assignment deliverable.
        Each item in `sections` can contain:
        - "heading": Section title
        - "paragraphs": List of text strings
        - "bullets": Optional list of bullet points
        - "table": Optional list of row lists [[col1, col2], [val1, val2]]
        """
        doc = Document()

        # Set Margins
        for section in doc.sections:
            section.top_margin = DocxInches(1)
            section.bottom_margin = DocxInches(1)
            section.left_margin = DocxInches(1)
            section.right_margin = DocxInches(1)

        # Title & Subtitle
        t_p = doc.add_paragraph()
        t_run = t_p.add_run(title)
        t_run.font.size = DocxPt(26)
        t_run.font.bold = True
        t_run.font.color.rgb = DocxRGBColor(17, 24, 39)
        t_p.paragraph_format.space_after = DocxPt(4)

        s_p = doc.add_paragraph()
        s_run = s_p.add_run(f"{subtitle} | Prepared by ONE DOTS")
        s_run.font.size = DocxPt(13)
        s_run.font.color.rgb = DocxRGBColor(107, 114, 128)
        s_p.paragraph_format.space_after = DocxPt(18)

        # Sections
        for sec in sections:
            heading = sec.get("heading")
            if heading:
                h_p = doc.add_heading(heading, level=1)
                h_p.paragraph_format.space_before = DocxPt(14)
                h_p.paragraph_format.space_after = DocxPt(6)

            for para in sec.get("paragraphs", []):
                p = doc.add_paragraph(para)
                p.paragraph_format.line_spacing = 1.15
                p.paragraph_format.space_after = DocxPt(6)

            for bullet in sec.get("bullets", []):
                doc.add_paragraph(bullet, style="List Bullet")

            table_data = sec.get("table")
            if table_data and len(table_data) > 0:
                table = doc.add_table(rows=len(table_data), cols=len(table_data[0]))
                table.style = "Table Grid"
                for r_idx, row in enumerate(table_data):
                    for c_idx, cell_value in enumerate(row):
                        cell = table.cell(r_idx, c_idx)
                        cell.text = str(cell_value)
                        if r_idx == 0:
                            for p in cell.paragraphs:
                                for r in p.runs:
                                    r.font.bold = True
                doc.add_paragraph().paragraph_format.space_after = DocxPt(10)

        clean_name = (output_filename or f"{title.lower().replace(' ', '_')[:30]}.docx")
        if not clean_name.endswith(".docx"):
            clean_name += ".docx"

        from config.settings import settings
        out_path = settings.DATA_DIR / "sandboxes" / self.agent_id / clean_name
        out_path.parent.mkdir(parents=True, exist_ok=True)
        doc.save(str(out_path))

        artifact = artifact_vault.register_file(
            agent_id=self.agent_id,
            name=clean_name,
            source_path=out_path,
            task_id=task_id,
            file_type="docx",
            metadata={"sections_count": len(sections), "title": title},
        )

        return {
            "success": True,
            "artifact_id": artifact.id,
            "filename": clean_name,
            "sections_count": len(sections),
            "file_path": artifact.file_path,
            "download_url": f"/api/artifacts/{artifact.id}/download",
            "message": f"Microsoft Word document '{clean_name}' with {len(sections)} sections generated successfully."
        }
